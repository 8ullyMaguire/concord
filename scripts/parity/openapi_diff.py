#!/usr/bin/env python3
"""Fail when a generated OpenAPI document removes or narrows a checked-in contract.

The baseline is the checked-in document; the current document is generated by
`make openapi`. Additive changes pass, breaking changes exit 1.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path


def load(path: Path):
    if not path.exists():
        print(f"openapi_diff: FAIL — missing document {path}")
        raise SystemExit(1)
    try:
        return json.loads(path.read_text())
    except json.JSONDecodeError as exc:
        print(f"openapi_diff: FAIL — unparseable document {path}: {exc}")
        raise SystemExit(1)


def compare_schemas(base: dict, current: dict) -> list[str]:
    problems: list[str] = []
    for name, old in base.items():
        if name not in current:
            problems.append(f"schema {name} removed")
            continue
        new = current[name]
        old_props = old.get("properties", {})
        new_props = new.get("properties", {})
        for field, old_prop in old_props.items():
            if field not in new_props:
                problems.append(f"{name}.{field} removed")
                continue
            new_prop = new_props[field]
            if old_prop.get("type") != new_prop.get("type"):
                problems.append(
                    f"{name}.{field} type {old_prop.get('type')} -> {new_prop.get('type')}"
                )
        for required in old.get("required", []):
            if required not in new.get("required", []):
                problems.append(f"{name}.{required} no longer required")
    return problems


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--base", default="docs/contracts/openapi.json")
    ap.add_argument("--current", default="docs/contracts/openapi.json")
    args = ap.parse_args()
    base = load(Path(args.base))
    current = load(Path(args.current))
    old_schemas = base.get("components", {}).get("schemas", {})
    new_schemas = current.get("components", {}).get("schemas", {})
    old_paths = base.get("paths", {})
    new_paths = current.get("paths", {})
    problems = [f"path {p} removed" for p in old_paths if p not in new_paths]
    problems += compare_schemas(old_schemas, new_schemas)
    if problems:
        for problem in problems:
            print(f"openapi_diff: FAIL — {problem}")
        return 1
    print(f"openapi_diff: PASS — {len(new_schemas)} schemas, {len(new_paths)} paths, 0 breaking changes")
    return 0


if __name__ == "__main__":
    sys.exit(main())
